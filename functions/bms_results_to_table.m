function T = bms_results_to_table(results)
%BMS_RESULTS_TO_TABLE Convert scenario results to a wide time-series table.

n = numel(results.time_s);
scenario_name = repmat(string(results.scenario_name), n, 1);
mode = string(results.mode(:));
time_s = results.time_s(:);
pack_voltage_V = results.pack_voltage_V(:);
charge_current_A = results.charge_current_A(:);
pack_imbalance_V = results.pack_imbalance_V(:);
V1_V = results.cell_voltage_V(:, 1);
V2_V = results.cell_voltage_V(:, 2);
V3_V = results.cell_voltage_V(:, 3);
V4_V = results.cell_voltage_V(:, 4);
SOC1 = results.soc(:, 1);
SOC2 = results.soc(:, 2);
SOC3 = results.soc(:, 3);
SOC4 = results.soc(:, 4);
T1_C = results.temperature_C(:, 1);
T2_C = results.temperature_C(:, 2);
T3_C = results.temperature_C(:, 3);
T4_C = results.temperature_C(:, 4);
BAL1 = double(results.balance_signal(:, 1));
BAL2 = double(results.balance_signal(:, 2));
BAL3 = double(results.balance_signal(:, 3));
BAL4 = double(results.balance_signal(:, 4));

T = table( ...
    scenario_name, time_s, mode, ...
    pack_voltage_V, charge_current_A, pack_imbalance_V, ...
    V1_V, V2_V, V3_V, V4_V, ...
    SOC1, SOC2, SOC3, SOC4, ...
    T1_C, T2_C, T3_C, T4_C, ...
    BAL1, BAL2, BAL3, BAL4, ...
    'VariableNames', { ...
    'scenario_name', 'time_s', 'mode', ...
    'pack_voltage_V', 'charge_current_A', 'pack_imbalance_V', ...
    'V1_V', 'V2_V', 'V3_V', 'V4_V', ...
    'SOC1', 'SOC2', 'SOC3', 'SOC4', ...
    'T1_C', 'T2_C', 'T3_C', 'T4_C', ...
    'BAL1', 'BAL2', 'BAL3', 'BAL4' ...
    });
end
